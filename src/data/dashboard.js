import { RULES } from './rules.js'

/* ============ 基础常量 ============ */
export const totalRules = RULES.length
export const INTL_ORGS = ['APEC', 'OECD', 'G20', 'UN', 'WB', 'WTO', 'IMF']

// 年度趋势（按发布日期统计）
const yearCnt = {}
RULES.forEach(r => { if (r.date) { const y = r.date.slice(0, 4); yearCnt[y] = (yearCnt[y] || 0) + 1 } })
export const TREND = {
  years: Object.keys(yearCnt).sort(),
  values: Object.keys(yearCnt).sort().map(y => yearCnt[y]),
}

// 国际组织/主体排名
const orgCntAll = {}
RULES.forEach(r => { orgCntAll[r.org] = (orgCntAll[r.org] || 0) + 1 })
export const TOP5 = Object.entries(orgCntAll).sort((a, b) => b[1] - a[1]).slice(0, 5)

// 热点议题：直接按表格「议题领域」原始取值分类（不做主题归并、不再有"其他"兜底）
export const TOPIC_PALETTE = [
  '#f45b5b', '#ff9440', '#f7d94c', '#4cd97b', '#3fd6e0', '#3f8cff', '#8a6bff', '#e05fd0',
  '#5fd0ff', '#7fe0a0', '#ffb02e', '#ff7a55', '#4fa8ff', '#b98cff', '#5ce0c0', '#ffd166',
  '#6ec1ff', '#e879a0', '#9fd85c', '#5c7fae',
]

// 总览细分（按字段字典的文件类型枚举映射）
export const SUB_MAP = [
  ['条约/协定', /协定|公约|条约/],
  ['法律/法规', /法规|条例|指令|示范法|规则/],
  ['行政规章',  /决定|决议|行政|令/],
  ['战略/框架', /战略|框架|政策|计划|通信/],
  ['标准/指南', /指南|建议|原则|手册|标准|最佳实践|示范/],
]

/* ============ 按年份范围派生统计 ============ */
export const RANK_COLORS = [['#a06bff', '#5b2fd6'], ['#4fa8ff', '#1a56c9'], ['#7fd0ff', '#2f6fd6'],
  ['#ffb02e', '#e07a1f'], ['#4cd97b', '#1f9e52']]

const HOTSPOT_TOP_N = 10

function buildHotspots(list, total) {
  const tc = {}
  list.forEach(r => {
    const k = (r.field || '未分类').trim()
    tc[k] = (tc[k] || 0) + 1
  })
  const all = Object.entries(tc).sort((a, b) => b[1] - a[1])
  const top = all.slice(0, HOTSPOT_TOP_N)
    .map(([name, value], i) => ({
      name, value,
      pct: (value / total * 100).toFixed(1) + '%',
      color: TOPIC_PALETTE[i % TOPIC_PALETTE.length],
    }))
  const rest = all.slice(HOTSPOT_TOP_N)
  if (rest.length) {
    const v = rest.reduce((s, [, n]) => s + n, 0)
    top.push({ name: `其他(${rest.length}类)`, value: v, pct: (v / total * 100).toFixed(1) + '%', color: '#5c7fae' })
  }
  return top
}
function buildSubs(list) {
  // 每条记录只归入第一个命中的类别，避免同一 fileType 命中多个正则被重复计数
  const sc = SUB_MAP.map(([k]) => [k, 0])
  let other = 0
  list.forEach(r => {
    const i = SUB_MAP.findIndex(([, re]) => re.test(r.fileType))
    if (i >= 0) sc[i][1]++
    else other++
  })
  sc.push(['报告/其他', other])
  return sc
}
function buildRank(list) {
  const oc = {}
  list.forEach(r => { oc[r.org] = (oc[r.org] || 0) + 1 })
  return Object.entries(oc).sort((a, b) => b[1] - a[1]).slice(0, 5)
    .map(([name, v], i) => ({ name, v, c1: RANK_COLORS[i][0], c2: RANK_COLORS[i][1] }))
}
export function statsForYears(years) {
  const yset = new Set(years)
  const list = RULES.filter(r => r.date && yset.has(r.date.slice(0, 4)))
  const total = list.length
  return {
    total,
    years,
    values: years.map(y => yearCnt[y] || 0),
    rankData: buildRank(list),
    hotspots: buildHotspots(list, total),
    org: INTL_ORGS.filter(o => orgCntAll[o] && list.some(r => r.org === o)).length,
    region: orgCntAll['欧盟'] && list.some(r => r.org === '欧盟') ? 1 : 0,
    subs: buildSubs(list),
  }
}
export function statsAll() {
  const total = RULES.length
  return {
    total,
    years: TREND.years,
    values: TREND.values,
    rankData: TOP5.map(([name, v], i) => ({ name, v, c1: RANK_COLORS[i][0], c2: RANK_COLORS[i][1] })),
    hotspots: buildHotspots(RULES, total),
    org: INTL_ORGS.filter(o => orgCntAll[o]).length,
    region: orgCntAll['欧盟'] ? 1 : 0,
    subs: buildSubs(RULES),
  }
}

